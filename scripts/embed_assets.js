/**
 * embed_assets.js
 * Reads built web assets from site/dist/
 * Gzip-compresses each asset and generates firmware/include/site_assets.h
 * Enables a single unified firmware binary containing the complete web control panel.
 */

const fs = require('fs');
const path = require('path');
const zlib = require('zlib');

const ROOT_DIR = path.resolve(__dirname, '..');
const DIST_DIR = path.join(ROOT_DIR, 'site', 'dist');
const OUTPUT_HEADER = path.join(ROOT_DIR, 'firmware', 'include', 'site_assets.h');

function getMimeType(filePath) {
  if (filePath.endsWith('.html')) return 'text/html';
  if (filePath.endsWith('.css')) return 'text/css';
  if (filePath.endsWith('.js')) return 'application/javascript';
  if (filePath.endsWith('.svg')) return 'image/svg+xml';
  if (filePath.endsWith('.ico')) return 'image/x-icon';
  if (filePath.endsWith('.json')) return 'application/json';
  return 'text/plain';
}

function collectFiles(dir, baseDir = dir) {
  let results = [];
  const list = fs.readdirSync(dir);
  for (const item of list) {
    const fullPath = path.join(dir, item);
    const stat = fs.statSync(fullPath);
    if (stat.isDirectory()) {
      results = results.concat(collectFiles(fullPath, baseDir));
    } else {
      const relPath = '/' + path.relative(baseDir, fullPath).replace(/\\/g, '/');
      results.push({ fullPath, relPath });
    }
  }
  return results;
}

function toHexArray(buffer) {
  const hex = [];
  for (let i = 0; i < buffer.length; i++) {
    hex.push('0x' + buffer[i].toString(16).padStart(2, '0'));
  }
  // Group in lines of 16 bytes
  const lines = [];
  for (let i = 0; i < hex.length; i += 16) {
    lines.push('  ' + hex.slice(i, i + 16).join(', '));
  }
  return lines.join(',\n');
}

function main() {
  if (!fs.existsSync(DIST_DIR)) {
    console.error(`[ERROR] dist directory does not exist: ${DIST_DIR}`);
    console.error('Run "npm run build" in site/ first.');
    process.exit(1);
  }

  const files = collectFiles(DIST_DIR);
  if (files.length === 0) {
    console.error(`[ERROR] No files found in: ${DIST_DIR}`);
    process.exit(1);
  }

  console.log(`[EMBED] Found ${files.length} built web assets to embed into firmware.`);

  const assetEntries = [];
  let arraysCode = '';

  files.forEach((file, index) => {
    const rawContent = fs.readFileSync(file.fullPath);
    const gzipped = zlib.gzipSync(rawContent, { level: 9 });
    const varName = `EMBEDDED_DATA_${index}`;
    const mime = getMimeType(file.relPath);

    arraysCode += `// ${file.relPath} (raw: ${rawContent.length} bytes, gzip: ${gzipped.length} bytes)\n`;
    arraysCode += `static const uint8_t ${varName}[] PROGMEM = {\n`;
    arraysCode += toHexArray(gzipped);
    arraysCode += `\n};\n\n`;

    assetEntries.push({
      path: file.relPath,
      varName,
      length: gzipped.length,
      mime,
    });

    // If index.html, also register "/"
    if (file.relPath === '/index.html') {
      assetEntries.push({
        path: '/',
        varName,
        length: gzipped.length,
        mime,
      });
    }
  });

  let tableCode = `struct EmbeddedSiteAsset {\n`;
  tableCode += `  const char* path;\n`;
  tableCode += `  const char* mimeType;\n`;
  tableCode += `  const uint8_t* data;\n`;
  tableCode += `  size_t length;\n`;
  tableCode += `};\n\n`;

  tableCode += `static const EmbeddedSiteAsset EMBEDDED_SITE_ASSETS[] = {\n`;
  for (const entry of assetEntries) {
    tableCode += `  { "${entry.path}", "${entry.mime}", ${entry.varName}, ${entry.length} },\n`;
  }
  tableCode += `};\n\n`;
  tableCode += `static const size_t EMBEDDED_SITE_ASSETS_COUNT = sizeof(EMBEDDED_SITE_ASSETS) / sizeof(EMBEDDED_SITE_ASSETS[0]);\n`;

  const headerContent = `/**
 * PanzerNavSystem - Embedded Production Web Assets
 * AUTO-GENERATED FILE - DO NOT EDIT MANUALLY
 * Generated by scripts/embed_assets.js
 *
 * This header embeds the complete gzipped web control panel in ESP8266 flash (PROGMEM).
 * Both firmware and website are combined into ONE SINGLE FLASH IMAGE.
 */

#ifndef SITE_ASSETS_H
#define SITE_ASSETS_H

#include <Arduino.h>

${arraysCode}
${tableCode}

#endif // SITE_ASSETS_H
`;

  fs.writeFileSync(OUTPUT_HEADER, headerContent, 'utf8');
  console.log(`[OK] Successfully generated ${OUTPUT_HEADER}`);
  console.log(`[OK] Embedded ${assetEntries.length} web routes into firmware binary.`);
}

main();
